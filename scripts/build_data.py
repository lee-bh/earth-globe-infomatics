# ---------------------------------------------------------------- life expectancy

def build_life_expectancy(countries):
    with (DATA / "life-expectancy-series.csv").open(encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        start = int(header[1])
        series = {r[0]: [float(v) for v in r[1:]] for r in reader}

    rows = {}
    year = None
    for r in read_csv("life-expectancy.csv"):
        cid = r["id"]
        if cid not in countries:
            raise SystemExit(f"life-expectancy.csv: unknown country id {cid!r}")
        year = r["year"]
        total, male, female = float(r["life_expectancy"]), float(r["male"]), float(r["female"])
        s = series.get(cid)
        details = [
            ["남성", f"{male:.1f}세"],
            ["여성", f"{female:.1f}세"],
            ["남녀 차이", f"여성이 {female - male:.1f}세 {'김' if female >= male else '짧음'}" if abs(female - male) >= 0.05 else "차이 없음"],
        ]
        if s:
            details.append([f"{start}년 대비", f"{s[-1] - s[0]:+.1f}세 ({s[0]:.1f}세 → {s[-1]:.1f}세)"])
        details.append(["기준 연도", f"{year}년 추정치"])
        rows[cid] = {
            "status": "value",
            "value": round(total, 2),
            "tip": f"남 {male:.1f} · 여 {female:.1f}",
            "details": details,
            "series": {"start": start, "values": s} if s else None,
        }
    push_indicator({
        "id": "life-expectancy",
        "order": 2,
        "group": "보건",
        "name": "기대수명",
        "longName": "출생 시 기대수명",
        "summary": "그해 태어난 아기가 현재의 연령별 사망률대로 산다고 할 때 기대되는 평균 수명",
        "asOf": f"{year}년",
        "unitLabel": "세 (남녀 전체)",
        "prefix": "", "suffix": "세", "bigUnit": "세", "decimals": 1,
        "compare": "diff",
        "thresholds": [60, 65, 70, 75, 80],
        "binLabels": ["~60", "60–65", "65–70", "70–75", "75–80", "80+"],
        "legendTitle": "출생 시 기대수명 (세)",
        "noneLabel": None,
        "seriesLabel": "기대수명 추이",
        "method": [
            f"유엔 인구국 세계인구전망(WPP) 2024의 {year}년 추정치입니다. 남녀 전체, 남성, 여성 값을 함께 보여 줍니다.",
            "기대수명은 실제로 사람들이 사는 나이가 아니라, 그해의 연령별 사망률이 평생 그대로 유지된다고 가정해 계산한 값입니다. 전쟁·감염병이 있던 해에는 크게 떨어질 수 있습니다.",
            f"오른쪽 추이 그래프는 {start}년부터 {year}년까지의 연도별 추정치입니다.",
        ],
        "sources": [
            {"name": "UN World Population Prospects 2024", "url": "https://population.un.org/wpp/"},
            {"name": "wpp2024 R 패키지 (UN 인구국 배포)", "url": "https://github.com/PPgp/wpp2024"},
        ],
        "rows": rows,
    })


def main():
    countries = build_countries()
    build_minimum_wage(countries)
    build_life_expectancy(countries)

    if len(sys.argv) > 1:
        topo = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
        write_js(DATA / "world-50m.js", "window.WORLD_TOPO = " + json.dumps(topo, separators=(",", ":")) + ";",
                 "Natural Earth 1:50m countries via world-atlas@2.0.2 (public domain).")


if __name__ == "__main__":
    main()
