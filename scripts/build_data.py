"""Build the page's data scripts from the CSV sources.

Usage:
    python3 scripts/build_data.py [path/to/world-atlas]      # the unpacked world-atlas@2.0.2 package

Outputs:
    data/countries.js                    window.COUNTRIES = {...}
    data/indicators/<indicator-id>.js    pushes one indicator onto window.INDICATORS
    data/world-50m.js, data/world-110m.js   window.WORLD_TOPO / WORLD_TOPO_LO (only when world-atlas is given);
                                            the globe draws 1:110m while moving and 1:50m at rest

Each indicator file is self-describing (name, unit, color bins, sources, method,
and one row per country), so adding an indicator means adding one builder
below and one <script> tag in index.html. Plain <script> files keep index.html
usable from file:// without a web server.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = DATA / "indicators"

PERIOD_KO = {"hour": "시간", "day": "일", "week": "주", "month": "월"}
PER_UNIT_KO = {"hour": "시간", "day": "일", "week": "주"}


def read_csv(name):
    with (DATA / name).open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(v, decimals=0):
    """1234567.8 -> '1,234,568'; small values keep up to `decimals` places without trailing zeros."""
    s = f"{v:,.{decimals}f}"
    if decimals and "." in s:
        s = s.rstrip("0").rstrip(".")
    return s


def local(v):
    return num(v, 0) if abs(v) >= 100 else num(v, 2)


def read_series(name):
    """Wide CSV (id, year1, year2, ...) -> (first year, {id: [value or None, ...]})."""
    with (DATA / name).open(encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        return int(header[1]), {r[0]: [float(v) if v else None for v in r[1:]] for r in reader}


def series_obj(start, values):
    """Trim leading/trailing gaps so the chart's x range matches the data."""
    if not values:
        return None
    idx = [i for i, v in enumerate(values) if v is not None]
    if len(idx) < 2:
        return None
    return {"start": start + idx[0], "values": values[idx[0]:idx[-1] + 1]}


def write_js(path, var_stmt, header):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"// {header}\n// Generated by scripts/build_data.py. Do not edit by hand.\n{var_stmt}\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def push_indicator(ind):
    write_js(
        OUT / f"{ind['id']}.js",
        "(window.INDICATORS = window.INDICATORS || []).push(" + json.dumps(ind, ensure_ascii=False, separators=(",", ":")) + ");",
        f"Indicator: {ind['name']}",
    )


# ---------------------------------------------------------------- countries

def build_countries():
    countries = {r["id"]: {"ko": r["name_ko"], "en": r["name_en"], "region": r["region"]} for r in read_csv("countries.csv")}
    write_js(DATA / "countries.js", "window.COUNTRIES = " + json.dumps(countries, ensure_ascii=False, separators=(",", ":")) + ";",
             "Country names (Korean/English) and regions, from data/countries.csv")
    return countries


