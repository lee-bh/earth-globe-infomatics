# ---------------------------------------------------------------- GDP per capita

MIN_GDP_YEAR = 2019  # same cut-off as scripts/import_sources.py


def people(n):
    """51712619 -> '5,171만 명', 1410710000 -> '14억 1,071만 명'."""
    if n < 1e5:
        return f"{n:,.0f}명"
    eok, man = divmod(round(n / 1e4), 10000)
    return (f"{eok}억 {man:,}만 명" if man else f"{eok}억 명") if eok else f"{man:,}만 명"


def build_gdp_per_capita(countries):
    start, series = read_series("gdp-per-capita-series.csv")
    rows = {}
    years = []
    for r in read_csv("gdp-per-capita.csv"):
        cid, year = r["id"], int(r["year"])
        years.append(year)
        gdp, pop, pc = float(r["gdp_usd"]), float(r["population"]), float(r["gdp_per_capita_usd"])
        s = series_obj(start, series.get(cid))
        details = [
            ["국내총생산(GDP)", f"{gdp / 1e12:,.2f}조 달러" if gdp >= 1e12 else f"{gdp / 1e8:,.0f}억 달러"],
            ["인구", people(pop)],
        ]
        if s and s["start"] <= 2000 and s["values"][0]:
            details.append([f"{s['start']}년 대비", f"{pc / s['values'][0]:.1f}배 (${s['values'][0]:,.0f} → ${pc:,.0f})"])
        details.append(["기준 연도", f"{year}년"])
        rows[cid] = {
            "status": "value",
            "value": round(pc, 1),
            "year": year,
            "tip": f"{year}년 · 인구 {people(pop)}",
            "details": details,
            "series": s,
        }
    latest = max(years)
    for cid, r in rows.items():
        if r["year"] != latest:
            r["note"] = f"{latest}년 값이 없어 {r['year']}년 값을 썼습니다."
