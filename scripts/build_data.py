def people(n):
    """51712619 -> '5,171만 명', 1410710000 -> '14억 1,071만 명'."""
    if n < 1e5:
        return f"{n:,.0f}명"
    eok, man = divmod(round(n / 1e4), 10000)
    return (f"{eok}억 {man:,}만 명" if man else f"{eok}억 명") if eok else f"{man:,}만 명"


