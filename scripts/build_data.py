"""Build the page's data scripts from the CSV source and the world-atlas TopoJSON.

Usage:
    python3 scripts/build_data.py [path/to/countries-50m.json]

Outputs:
    data/minimum-wage.js  -> window.MINIMUM_WAGE = {...}
    data/world-50m.js     -> window.WORLD_TOPO = {...}   (only when a TopoJSON path is given)

Loading the data as plain <script> files keeps index.html usable from file://
without a local web server.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "minimum-wage.csv"

PERIOD_KO = {"hour": "시간", "day": "일", "week": "주", "month": "월"}


def build_wages():
    rows = []
    with CSV_PATH.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            item = {
                "id": r["id"],
                "nameKo": r["name_ko"],
                "nameEn": r["name_en"],
                "region": r["region"],
                "status": r["status"],
                "source": r["source"],
                "note": r["note"],
            }
            if r["status"] == "statutory":
                amount = float(r["amount"])
                per_month = float(r["per_month"])
                fx = float(r["fx_per_usd"])
                monthly_local = amount * per_month
                item.update(
                    amount=amount,
                    currency=r["currency"],
                    period=r["period"],
                    periodKo=PERIOD_KO[r["period"]],
                    perMonth=per_month,
                    effective=r["effective"],
                    fxPerUsd=fx,
                    monthlyLocal=round(monthly_local, 2),
                    monthlyUsd=round(monthly_local / fx, 1),
                )
            rows.append(item)
    rows.sort(key=lambda x: -x.get("monthlyUsd", -1))
    return rows


def main():
    wages = build_wages()
    payload = {
        "asOf": "2026-10",
        "fxDate": "2026-10 초",
        "countries": wages,
    }
    out = ROOT / "data" / "minimum-wage.js"
    out.write_text(
        "// Generated by scripts/build_data.py from data/minimum-wage.csv. Do not edit by hand.\n"
        "window.MINIMUM_WAGE = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)} ({len(wages)} countries)")

    if len(sys.argv) > 1:
        topo = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
        world = ROOT / "data" / "world-50m.js"
        world.write_text(
            "// Natural Earth 1:50m countries via world-atlas@2.0.2 (public domain).\n"
            "window.WORLD_TOPO = " + json.dumps(topo, separators=(",", ":")) + ";\n",
            encoding="utf-8",
        )
        print(f"wrote {world.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
